// ── Init i18next ───────────────────────────────────────────────
export const i18nReady = i18next.init({
  lng: localStorage.getItem(STORAGE_KEY) || "en",
  fallbackLng: "en",
  resources,
  interpolation: { escapeValue: false },
});

export const t = (key, opts) => i18next.t(key, opts);

export const getLang = () => i18next.language;

export async function setLang(lang) {
  await i18next.changeLanguage(lang);
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
}

let _langSwitching = false;

export async function toggleLang() {
  if (_langSwitching) return;
  _langSwitching = true;
  try {
    await setLang(i18next.language === "en" ? "es" : "en");
  } finally {
    _langSwitching = false;
  }
}

export function onLangChange(fn) {
  i18next.on("languageChanged", fn);
  return () => i18next.off("languageChanged", fn);
}

i18nReady.then(() => {
  document.documentElement.lang = i18next.language;
});
